# The game APK's launcher icon from the player's own disc: the dashboard icon
# in game/files/default.xex (64x64), made into Android launcher icons in
# android/app/src/disc/res (git-ignored, like ppc/). When that folder exists
# the Gradle build uses it (ic_launcher_disc); otherwise the APK keeps its own
# speedometer icon, as the CI test APK always does. Nothing of the game is ever
# committed: run this where the game APK is built, after prepare_recompiler.sh.
#
# An HD picture of the owner's choosing at private/app-icon.png (or .jpg;
# private/ is git-ignored) is used instead of the disc's 64x64 icon, its
# centre square.
#
#   scripts/android/prepare_disc_icon.sh [path/to/default.xex]
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
XEX="${1:-$ROOT/game/files/default.xex}"
XR="$ROOT/tools/XenonRecomp"
[ -f "$XEX" ] || { echo "No default.xex at $XEX" >&2; exit 1; }
[ -f "$XR/build/XenonUtils/libXenonUtils.a" ] || { echo 'Run scripts/android/prepare_recompiler.sh first' >&2; exit 1; }
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
LIBS=$(find "$XR/build" -name '*.a' ! -path '*XenonAnalyse*')
"${CXX:-clang++}" -std=c++20 -O1 -I"$XR/XenonUtils" -I"$XR/thirdparty" -I"$XR/thirdparty/simde" \
    "$ROOT/scripts/android/title_icon.cpp" "$XR/build/XenonUtils/libXenonUtils.a" $LIBS -o "$WORK/title_icon"
"$WORK/title_icon" "$XEX" "$WORK/icon.png"
for pic in "$ROOT/private/app-icon.png" "$ROOT/private/app-icon.jpg"; do
    [ -f "$pic" ] && { cp "$pic" "$WORK/icon.png"; echo "HD icon picture: $pic"; break; }
done
python3 -I - "$WORK/icon.png" "$ROOT/android/app/src/disc/res" <<'PY'
# Adaptive icon: black background; the art centred at 66 of the 108dp
# foreground (the safe zone: launchers show the centre 72, masks keep 66).
import os, sys
from PIL import Image, ImageDraw
src, res = sys.argv[1], sys.argv[2]
art = Image.open(src).convert("RGBA")
side = min(art.size)  # an HD picture: its centre square
art = art.crop(((art.width - side) // 2, (art.height - side) // 2, (art.width + side) // 2, (art.height + side) // 2))
for name, scale in (("mdpi", 1), ("hdpi", 1.5), ("xhdpi", 2), ("xxhdpi", 3), ("xxxhdpi", 4)):
    d = os.path.join(res, "mipmap-" + name); os.makedirs(d, exist_ok=True)
    full, inner = round(108 * scale), round(66 * scale)
    tile = art.resize((inner, inner), Image.LANCZOS)
    mask = Image.new("L", (inner, inner), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, inner - 1, inner - 1), radius=round(8 * scale), fill=255)
    fg = Image.new("RGBA", (full, full), (0, 0, 0, 0))
    fg.paste(tile, ((full - inner) // 2, (full - inner) // 2), mask)
    fg.save(os.path.join(d, "ic_launcher_disc_foreground.png"))
    legacy = art.resize((round(48 * scale),) * 2, Image.LANCZOS)  # before Android 8
    legacy.save(os.path.join(d, "ic_launcher_disc.png"))
d = os.path.join(res, "mipmap-anydpi-v26"); os.makedirs(d, exist_ok=True)
for n in ("ic_launcher_disc.xml", "ic_launcher_disc_round.xml"):
    open(os.path.join(d, n), "w").write(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/android/prepare_disc_icon.sh from the player\'s disc. Never committed. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_disc_foreground" />\n'
        '</adaptive-icon>\n')
for name in ("mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"):
    p = os.path.join(res, "mipmap-" + name)
    Image.open(os.path.join(p, "ic_launcher_disc.png")).save(os.path.join(p, "ic_launcher_disc_round.png"))
print("disc icon ->", res)
PY
